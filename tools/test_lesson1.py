"""第 1 堂「開始寫 Python」流程測試（第 2.1 版，一次一章）。python3 tools/test_lesson1.py"""
import asyncio, sys, os
from playwright.async_api import async_playwright

URL = 'file://' + os.path.abspath(os.path.join(os.path.dirname(__file__), '..', 'lesson1', 'index.html'))
errors, res = [], []
def check(name, ok, extra=''):
    res.append((name, ok)); print(('PASS ' if ok else 'FAIL ') + name + (' — ' + extra if extra else ''))
async def current(pg): return await pg.evaluate('document.querySelector("section.card.current").id')
async def next_disabled(pg): return await pg.locator('#btnNext').is_disabled()
async def go_next(pg): await pg.click('#btnNext'); await pg.wait_for_timeout(250)
async def predict(pg, box, pick):
    await box.locator('.opt').nth(pick).click(); await box.locator('.btn.go').click(); await pg.wait_for_timeout(900)
async def open_help(box): await box.locator('details.help summary').click()

async def main():
    async with async_playwright() as p:
        b = await p.chromium.launch()
        pg = await b.new_page(viewport={'width': 1200, 'height': 900})
        pg.on('console', lambda m: errors.append(m.text) if m.type == 'error' else None)
        pg.on('pageerror', lambda e: errors.append(str(e)))
        await pg.goto(URL); await pg.wait_for_timeout(800)
        check('Skulpt 載入', '就緒' in await pg.text_content('#pyStatus'))
        html = await pg.content()
        check('頁面沒有 Scratch／Arduino 字眼', 'Scratch' not in html and 'Arduino' not in html)
        check('只顯示一章', await pg.locator('section.card.current').count() == 1 and await current(pg) == 's0')
        check('登記前「下一章」停用', await next_disabled(pg))
        await pg.fill('#stName', '測試同學'); await pg.fill('#stClass', '3A'); await pg.fill('#stNo', '12'); await pg.click('#btnStart'); await pg.wait_for_timeout(300)
        check('登記後進入第 1 章', await current(pg) == 's1')
        # 第 1 章
        c1 = pg.locator('#c1 .predict'); ex1 = pg.locator('#c1 .exbox')
        await predict(pg, c1.nth(0), 0)
        sh = await c1.nth(0).locator('.shell').text_content()
        check('試一試 1 Shell 顯示 %Run 及 Hello, World!', '%Run' in sh and 'Hello, World!' in sh, sh)
        d = pg.locator('#demo1 .th')
        check('第 1 章有完整版 Thonny（標題列、工具列、Variables）', await d.locator('.ttl').count() == 1 and await d.locator('.vars').count() == 1)
        await d.locator('textarea').fill('print("Hi")'); await d.locator('button.run').click(); await pg.wait_for_timeout(700)
        check('示範 Thonny 執行成功', 'Hi' in await d.locator('.shell').text_content())
        check('行號隨行數更新', (await d.locator('.gut').text_content()).strip() == '1')
        check('試一試後「下一章」仍停用（練習未做）', await next_disabled(pg))
        check('底部狀態提示還有練習', '練習' in await pg.text_content('#navStatus'))
        await ex1.locator('[data-check]').click(); await pg.wait_for_timeout(300)
        check('練習 1 未填 ____ 被拒', '____' in await ex1.locator('[data-fb]').text_content())
        await ex1.locator('textarea').fill('Print("Hello, Python!")'); await ex1.locator('[data-check]').click(); await pg.wait_for_timeout(900)
        o = await ex1.locator('.shell').text_content(); at = await ex1.locator('.assist').text_content()
        check('練習 1 大小寫錯誤：Thonny 式 Traceback 及 Assistant', 'Traceback' in o and "NameError: name 'Print' is not defined" in o and '大小寫' in at, o[:120])
        await ex1.locator('textarea').fill('print("Hello, Python!")'); await ex1.locator('[data-check]').click(); await pg.wait_for_timeout(900)
        check('練習 1 完成 5 分', '5 分' in await ex1.locator('[data-fb]').text_content())
        check('第 1 章完成後狀態 9 / 9', '9 / 9' in await pg.text_content('#navStatus'), await pg.text_content('#navStatus'))
        check('「下一章」可用', not await next_disabled(pg))
        await go_next(pg); check('進入第 2 章', await current(pg) == 's2')
        # 第 2 章：估錯、看答案
        c2 = pg.locator('#c2 .predict'); ex2 = pg.locator('#c2 .exbox')
        await predict(pg, c2.nth(0), 0)
        o = await c2.nth(0).locator('.shell').text_content(); at = await c2.nth(0).locator('.assist').text_content()
        check('縮排錯誤顯示 IndentationError 及 Assistant 解釋', 'IndentationError: unexpected indent' in o and '空格' in at, o[:120])
        check('估錯顯示正確選項字母', '答案是 C' in await c2.nth(0).locator('.fb').text_content())
        await open_help(ex2); await ex2.locator('[data-a]').click()
        await ex2.locator('textarea').fill('print("Python 分大小寫")\nprint("行首不可以有空格")'); await ex2.locator('[data-check]').click(); await pg.wait_for_timeout(900)
        check('練習 2 看答案後只得 1 分', '1 分' in await ex2.locator('[data-fb]').text_content())
        check('第 2 章 1 分', '1 / 9' in await pg.text_content('#navStatus'))
        await go_next(pg); check('進入第 3 章', await current(pg) == 's3')
        # 第 3 章
        c3 = pg.locator('#c3 .predict'); ex3 = pg.locator('#c3 .exbox')
        await predict(pg, c3.nth(0), 2); await predict(pg, c3.nth(1), 1)
        await ex3.locator('textarea').fill('print("你好")\nprint("10")\nprint("一共", 10, "件")'); await ex3.locator('[data-check]').click(); await pg.wait_for_timeout(900)
        check('練習 3 用引號包數字被拒', '不要用引號' in await ex3.locator('[data-fb]').text_content())
        await ex3.locator('textarea').fill('print("你好")\nprint(99)\nprint("一共", 10, "件")'); await ex3.locator('[data-check]').click(); await pg.wait_for_timeout(900)
        check('錯兩次後自動出提示', await ex3.locator('details.help .fb').count() >= 1)
        await ex3.locator('textarea').fill('print("你好")\nprint(10)\nprint("一共", 10, "件")'); await ex3.locator('[data-check]').click(); await pg.wait_for_timeout(900)
        check('第 3 章 13 分', '13 / 13' in await pg.text_content('#navStatus'), await pg.text_content('#navStatus'))
        await go_next(pg); check('進入第 4 章', await current(pg) == 's4')
        # 第 4 章
        c4 = pg.locator('#c4 .predict'); ex4 = pg.locator('#c4 .exbox')
        await predict(pg, c4.nth(0), 1)
        await ex4.locator('textarea').fill('print("開始")\nprint("完結")'); await ex4.locator('[data-check]').click(); await pg.wait_for_timeout(900)
        fbt = await ex4.locator('[data-fb]').text_content()
        check('練習 4 刪行而非註解被拒', '最頂' in fbt or '註解掉' in fbt, fbt)
        await ex4.locator('textarea').fill('# 練習 4\nprint("開始")\n# print("測試中，之後刪去")\nprint("完結")'); await ex4.locator('[data-check]').click(); await pg.wait_for_timeout(900)
        check('第 4 章 9 分', '9 / 9' in await pg.text_content('#navStatus'))
        await go_next(pg); check('進入作品', await current(pg) == 's5')
        # 作品
        t = pg.locator('#tiers .tier')
        await t.nth(0).locator('textarea').fill('print("==========")\nprint("陳大文")\nprint("3A")\nprint("==========")'); await t.nth(0).locator('[data-check]').click(); await pg.wait_for_timeout(900)
        check('必做內容不足 5 行被拒', '最少要 5 行' in await t.nth(0).locator('[data-fb]').text_content())
        check('必做未完成「下一章」停用', await next_disabled(pg))
        good = 'print("==========")\nprint("陳大文")\nprint("3A")\nprint("興趣：打籃球")\nprint("食物：魚蛋")\nprint("想去：日本")\nprint("==========")'
        await t.nth(0).locator('textarea').fill(good); await t.nth(0).locator('[data-check]').click(); await pg.wait_for_timeout(900)
        check('必做完成 25 分', '25 分' in await pg.text_content('#tfb_t1'))
        check('必做完成後可去小測', not await next_disabled(pg))
        await t.nth(1).locator('textarea').fill('# 名牌 陳大文\n' + good + '\nprint("出生年份：", "2026 - 15")  # 計算'); await t.nth(1).locator('[data-check]').click(); await pg.wait_for_timeout(900)
        check('進階計算放在引號內被拒', '不在引號內' in await t.nth(1).locator('[data-fb]').text_content())
        await t.nth(1).locator('textarea').fill('# 名牌 陳大文\n' + good + '\nprint("出生年份：", 2026 - 15)  # 計算'); await t.nth(1).locator('[data-check]').click(); await pg.wait_for_timeout(900)
        check('進階完成 10 分', '10 分' in await pg.text_content('#tfb_t2'))
        await t.nth(2).locator('textarea').fill('print("   *   ")\nprint("  ***  ")\nprint(" ***** ")\nprint("*******")\nprint("  |||  ")\nprint("  |||  ")'); await t.nth(2).locator('[data-check]').click(); await pg.wait_for_timeout(900)
        check('挑戰完成 5 分', '5 分' in await pg.text_content('#tfb_t3'))
        await go_next(pg); check('進入小測', await current(pg) == 's6')
        q = pg.locator('#quiz .predict')
        check('小測沒有執行器', await q.nth(0).locator('.runner').count() == 0)
        await predict(pg, q.nth(0), 0); await predict(pg, q.nth(1), 1); await predict(pg, q.nth(2), 2)
        await pg.click('#btnExit'); await pg.wait_for_timeout(200)
        check('自評太短被拒', '一句' in await pg.text_content('#exitFb'))
        await pg.fill('#reflect', '我先看 Shell 紅字最後一行，再找行號。'); await pg.click('#btnExit'); await pg.wait_for_timeout(800)
        check('提交後進入報告', await current(pg) == 's7')
        # 9 + 1 + 13 + 9 + 40 + (5+5+0+5) = 87
        check('總分 87', await pg.text_content('#scoreNow') == '87', await pg.text_content('#scoreNow'))
        check('報告有驗證碼', '驗證碼' in await pg.text_content('#reportBox'))
        # 進度列可回看已完成章
        await pg.click('#steps button[data-i="2"]'); await pg.wait_for_timeout(200)
        check('進度列可跳回第 2 章', await current(pg) == 's2')
        check('回看時「下一章」可用', not await next_disabled(pg))
        await pg.reload(); await pg.wait_for_timeout(800)
        check('重新載入後分數保留', await pg.text_content('#scoreNow') == '87')
        check('重新載入後停留在上次的章', await current(pg) == 's2')
        await pg.click('#steps button[data-i="6"]'); await pg.wait_for_timeout(200)
        check('重新載入後小測鎖定', await pg.locator('#btnExit').is_disabled())
        await pg.click('#btnTeacher'); await pg.fill('#pin', 'wrong'); await pg.click('#pinGo'); await pg.wait_for_timeout(200)
        check('錯 PIN 拒絕', 'PIN 不正確' in await pg.text_content('#tpanel'))
        await pg.fill('#pin', 'py2026'); await pg.click('#pinGo'); await pg.wait_for_timeout(200)
        check('正確 PIN 顯示答案', '練習 1' in await pg.text_content('#tpanel'))
        await pg.locator('#pinX').click()
        await pg.click('#steps button[data-i="1"]'); await pg.wait_for_timeout(300)
        await pg.screenshot(path='/tmp/py3_shot_desktop.png', full_page=True)
        await pg.click('#steps button[data-i="5"]'); await pg.wait_for_timeout(300)
        await pg.screenshot(path='/tmp/py3_shot_desktop5.png', full_page=True)
        # 手機
        m = await b.new_page(viewport={'width': 390, 'height': 844})
        await m.goto(URL); await m.wait_for_timeout(800)
        sw = await m.evaluate('document.documentElement.scrollWidth')
        check('手機闊度無橫向捲動（登記頁）', sw <= 392, str(sw))
        await m.click('#btnTeacher'); await m.fill('#pin', 'py2026'); await m.click('#pinGo'); await m.wait_for_timeout(200); await m.click('#tpanel [data-j="3"]'); await m.wait_for_timeout(300)
        sw = await m.evaluate('document.documentElement.scrollWidth')
        check('手機闊度無橫向捲動（第 3 章）', sw <= 392, str(sw))
        top = await m.evaluate('document.querySelector(".topbar").getBoundingClientRect().height')
        check('頂部欄不超過 110px', top <= 110, str(top))
        await m.screenshot(path='/tmp/py3_shot_mobile.png', full_page=True)
        await b.close()
    real = [e for e in errors if 'ERR_TUNNEL_CONNECTION_FAILED' not in e and 'ERR_INTERNET_DISCONNECTED' not in e]
    check('沒有 console 錯誤（不計 Google Fonts）', not real, '; '.join(real)[:300])
    fails = [r for r in res if not r[1]]
    print(f'\n{len(res)-len(fails)} / {len(res)} 通過')
    sys.exit(1 if fails else 0)

asyncio.run(main())
