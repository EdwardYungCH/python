"""第 3 堂「數字與運算符」流程測試。python3 tools/test_lesson3.py"""
import asyncio, sys, os
sys.path.insert(0, os.path.dirname(__file__))
from playwright.async_api import async_playwright
from testlib import *

async def main():
    async with async_playwright() as p:
        b = await p.chromium.launch(); pg = await b.new_page(viewport={'width': 1200, 'height': 900}); wire(pg)
        await pg.goto(url_of(3)); await pg.wait_for_timeout(800)
        check('Skulpt 載入', '就緒' in await pg.text_content('#pyStatus'))
        html = await pg.content(); check('沒有舊堂殘留', 'Hello, World' not in html and '自我介紹' not in html)
        await register(pg); check('進入第 1 章', await current(pg) == 's1')
        c1 = pg.locator('#c1 .predict'); ex1 = pg.locator('#c1 .exbox')
        await predict(pg, c1.nth(0), 1); check('試一試 1 輸出 2.0', '2.0' in await c1.nth(0).locator('.shell').text_content())
        await check_ex(pg, ex1, 'total = 235\naverage = total / 3\nprint(round(average, 2))'); check('練習 1 保留 2 位被拒', '不一樣' in await fb(ex1))
        await check_ex(pg, ex1, 'total = 235\naverage = total / 3\nprint(round(average, 1))'); check('練習 1 完成', '5 分' in await fb(ex1))
        await go_next(pg)
        c2 = pg.locator('#c2 .predict'); ex2 = pg.locator('#c2 .exbox')
        await predict(pg, c2.nth(0), 0); await predict(pg, c2.nth(1), 1)
        await check_ex(pg, ex2, 'money = 37\nprint("十元", money / 10, "個")\nprint("一元", money % 10, "個")'); check('練習 2 用 / 被拒', '商' in await fb(ex2))
        await check_ex(pg, ex2, 'money = 37\nprint("十元", money // 10, "個")\nprint("一元", money % 10, "個")'); check('練習 2 完成', '5 分' in await fb(ex2))
        check('第 2 章 9 / 13', '9 / 13' in await pg.text_content('#navStatus'), await pg.text_content('#navStatus'))
        await go_next(pg)
        c3 = pg.locator('#c3 .predict'); ex3 = pg.locator('#c3 .exbox')
        await predict(pg, c3.nth(0), 0)
        await check_ex(pg, ex3, 'total = 0\ntotal = total + 12\ntotal = total + 8\ntotal = total * 0.8\nprint(total)'); check('練習 3 不用簡寫被拒', '簡寫' in await fb(ex3))
        await check_ex(pg, ex3, 'total = 0\ntotal += 12\ntotal += 8\ntotal *= 0.8\nprint(total)'); check('練習 3 完成', '5 分' in await fb(ex3))
        await go_next(pg)
        c4 = pg.locator('#c4 .predict'); ex4 = pg.locator('#c4 .exbox')
        await predict(pg, c4.nth(0), 0)
        await check_ex(pg, ex4, 'score = 60\nprint(score = 60)\nprint(score != 60)\nprint(score > 50)')
        sh = await ex4.locator('.shell').text_content(); at = await ex4.locator('.assist').text_content(); check('單等號比較 → TypeError 及 Assistant 解釋 ==', 'TypeError' in sh and '==' in at, at)
        await check_ex(pg, ex4, 'score = 60\nprint(score == 60)\nprint(score != 60)\nprint(score > 50)'); check('練習 4 完成', '5 分' in await fb(ex4))
        await go_next(pg); check('進入作品', await current(pg) == 's5')
        t = pg.locator('#tiers .tier')
        await check_ex(pg, t.nth(0), 'h = input("身高：")\nw = input("體重：")\nprint(round(w / h ** 2, 1))', inputs=['1.65', '55'])
        check('BMI 未 float() 出錯被指出', 'float()' in await fb(t.nth(0)), await fb(t.nth(0)))
        await check_ex(pg, t.nth(0), 'h = float(input("身高："))\nw = float(input("體重："))\nprint("你的 BMI 是", round(w / h ** 2, 1))', inputs=['1.65', '55'])
        check('必做完成 25 分', '25 分' in await pg.text_content('#tfb_t1'))
        await check_ex(pg, t.nth(1), 'm = int(input("金額："))\nprint("50 元", m // 50, "張")\nm = m % 50\nprint("10 元", m // 10, "張")\nm = m % 10\nprint("1 元", m, "個")', inputs=['87'])
        check('進階完成 10 分', '10 分' in await pg.text_content('#tfb_t2'), await fb(t.nth(1)))
        await check_ex(pg, t.nth(2), 's = int(input("秒："))\nprint(s // 3600, "小時", s % 3600 // 60, "分", s % 60, "秒")', inputs=['3725'])
        check('挑戰完成 5 分', '5 分' in await pg.text_content('#tfb_t3'), await fb(t.nth(2)))
        await go_next(pg); await submit_quiz(pg, [0, 1, 3], '我把 // 和 % 搞混了，試一次就記得。')
        check('提交後進入報告', await current(pg) == 's7')
        # 9+9+9+9 + 40 + 20 = 96
        await common_tail(pg, b, 3, 96, 'round(average, 1)')
        await b.close()
    finish()

asyncio.run(main())
