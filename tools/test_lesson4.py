"""第 4 堂「If…Else」流程測試。python3 tools/test_lesson4.py"""
import asyncio, sys, os
sys.path.insert(0, os.path.dirname(__file__))
from playwright.async_api import async_playwright
from testlib import *

async def main():
    async with async_playwright() as p:
        b = await p.chromium.launch(); pg = await b.new_page(viewport={'width': 1200, 'height': 900}); wire(pg)
        await pg.goto(url_of(4)); await pg.wait_for_timeout(800)
        check('Skulpt 載入', '就緒' in await pg.text_content('#pyStatus'))
        check('標題是第 4 堂', '第 4 堂' in await pg.text_content('.topbar'))
        await register(pg); check('進入第 1 章', await current(pg) == 's1')
        c1 = pg.locator('#c1 .predict'); ex1 = pg.locator('#c1 .exbox')
        await predict(pg, c1.nth(0), 1)
        await check_ex(pg, ex1, 'score = 60\nif score >= 50\nprint("合格")\nprint("完")')
        sh = await ex1.locator('.shell').text_content(); check('漏冒號 → SyntaxError', 'SyntaxError' in sh, sh[-100:])
        await check_ex(pg, ex1, 'score = 60\nif score >= 50:\n    print("合格")\n    print("完")'); check('「完」也縮排被拒', '不要縮排' in await fb(ex1), await fb(ex1))
        await check_ex(pg, ex1, 'score = 60\nif score >= 50:\n    print("合格")\nprint("完")'); check('練習 1 完成', '5 分' in await fb(ex1))
        await go_next(pg)
        c2 = pg.locator('#c2 .predict'); ex2 = pg.locator('#c2 .exbox')
        await predict(pg, c2.nth(0), 0); check('估錯顯示答案 B', '答案是 B' in await c2.nth(0).locator('.fb').text_content())
        await check_ex(pg, ex2, 'temp = 22\nif temp >= 28:\n    print("熱")\nif temp >= 18:\n    print("舒適")\nelse:\n    print("冷")'); check('用兩個 if 而非 elif 被拒', 'elif' in await fb(ex2), await fb(ex2))
        await check_ex(pg, ex2, 'temp = 22\nif temp >= 28:\n    print("熱")\nelif temp >= 18:\n    print("舒適")\nelse:\n    print("冷")'); check('練習 2 完成', '5 分' in await fb(ex2))
        await go_next(pg)
        c3 = pg.locator('#c3 .predict'); ex3 = pg.locator('#c3 .exbox')
        await predict(pg, c3.nth(0), 1); await predict(pg, c3.nth(1), 1)
        await check_ex(pg, ex3, 'age = 15\nif age >= 12 or age <= 17:\n    print("青少年票")\nelse:\n    print("普通票")'); check('用 or 被拒', 'and' in await fb(ex3))
        await check_ex(pg, ex3, 'age = 15\nif age >= 12 and age <= 17:\n    print("青少年票")\nelse:\n    print("普通票")'); check('練習 3 完成', '5 分' in await fb(ex3))
        check('第 3 章 13 / 13', '13 / 13' in await pg.text_content('#navStatus'))
        await go_next(pg)
        c4 = pg.locator('#c4 .predict'); ex4 = pg.locator('#c4 .exbox')
        await predict(pg, c4.nth(0), 2)
        await check_ex(pg, ex4, 'raining = True\nwindy = True\nif raining:\n    print("帶傘")\nif windy:\n    print("小心")\nelse:\n    print("好天")'); check('裏面 if 沒縮排被拒', '8 格' in await fb(ex4) or '縮排' in await fb(ex4), await fb(ex4))
        await check_ex(pg, ex4, 'raining = True\nwindy = True\nif raining:\n    print("帶傘")\n    if windy:\n        print("小心")\nelse:\n    print("好天")'); check('練習 4 完成', '5 分' in await fb(ex4))
        await go_next(pg); check('進入作品', await current(pg) == 's5')
        t = pg.locator('#tiers .tier')
        await check_ex(pg, t.nth(0), 'age = int(input("你幾歲？"))\nif age < 12:\n    print("兒童票 40 元")\nelse:\n    print("成人票 80 元")')
        check('必做漏長者被多組測試捉到', '70' in await fb(t.nth(0)), await fb(t.nth(0)))
        await check_ex(pg, t.nth(0), 'age = int(input("你幾歲？"))\nif age < 12:\n    print("兒童票 40 元")\nelif age >= 65:\n    print("長者票 40 元")\nelse:\n    print("成人票 80 元")')
        check('必做完成 25 分', '25 分' in await pg.text_content('#tfb_t1'), await fb(t.nth(0)))
        sh = await t.nth(0).locator('.shell').text_content(); check('檢查後 Shell 顯示測試輸入的執行', '%Run' in sh and '兒童' in sh, sh[:100])
        await check_ex(pg, t.nth(1), 'bmi = float(input("BMI："))\nif bmi < 18.5:\n    print("過輕")\nelif bmi < 23:\n    print("正常")\nelif bmi < 25:\n    print("過重")\nelse:\n    print("肥胖")')
        check('進階完成 10 分', '10 分' in await pg.text_content('#tfb_t2'), await fb(t.nth(1)))
        await check_ex(pg, t.nth(2), 'year = int(input("年份："))\nif year % 4 == 0:\n    print("閏年")\nelse:\n    print("不是閏年")')
        check('挑戰漏 100/400 被 1900 捉到', '1900' in await fb(t.nth(2)), await fb(t.nth(2)))
        await check_ex(pg, t.nth(2), 'year = int(input("年份："))\nif (year % 4 == 0 and year % 100 != 0) or year % 400 == 0:\n    print("閏年")\nelse:\n    print("不是閏年")')
        check('挑戰完成 5 分', '5 分' in await pg.text_content('#tfb_t3'))
        await go_next(pg); await submit_quiz(pg, [1, 0, 1], '我忘記了冒號，看到 SyntaxError 才發現。')
        check('提交後進入報告', await current(pg) == 's7')
        # 9+5+13+9 + 40 + 20 = 96
        await common_tail(pg, b, 4, 96, 'if、elif、else', mobile_chapter=3)
        await b.close()
    finish()

asyncio.run(main())
